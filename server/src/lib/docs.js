// Generates docs/api.md and docs/rbac.md from the code itself, so the documents cannot drift from what the
// server enforces: the API list is read from the mounted routers (with the permissions their guards demand),
// the role table from shared/permissions.js. `npm run docs` writes them; a test fails if they are stale.
import { PERMISSIONS, PERMISSION_KEYS, ROLES, ROLE_KEYS, ROLE_PERMISSIONS } from '@ledgernepal/shared/permissions';

const NOTE = '<!-- Generated by `npm run docs`. Do not edit by hand: change the code and regenerate. -->';

/** Every route of the app: { method, path, access } where access says who may call it. */
export function collectRoutes(app) {
  const routes = [];
  for (const [mountPath, router] of app.locals.mountedRouters) {
    for (const layer of router.stack) {
      if (!layer.route) continue;
      const path = layer.route.path === '/' ? '' : layer.route.path;
      for (const method of new Set(layer.route.stack.map((l) => l.method).filter(Boolean))) {
        const handlers = layer.route.stack.filter((l) => l.method === method).map((l) => l.handle);
        const guards = handlers.map((h) => h.guard).filter(Boolean);
        const permissions = handlers.filter((h) => h.guard === 'permission').flatMap((h) => h.permissions);
        let access = 'Public';
        if (permissions.length > 0) access = permissions.map((p) => `\`${p}\``).join(' + ');
        else if (guards.includes('owner')) access = 'Owner only';
        else if (guards.includes('authenticate')) access = 'Signed in';
        routes.push({ method: method.toUpperCase(), path: `${mountPath}${path}`, access });
      }
    }
  }
  return routes;
}

export function renderApiDoc(app) {
  const routes = collectRoutes(app);
  const groups = new Map();
  for (const route of routes) {
    const group = route.path.split('/')[2] ?? 'other';
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(route);
  }
  const lines = [
    '# API reference',
    '',
    NOTE,
    '',
    'Every endpoint is under `/api`. Business data endpoints act on the **active business of the session**; the client never sends a business id. All writes need the `X-CSRF-Token` header and a JSON body. Responses are `{ "data": ... }` (lists add `"meta"`) or `{ "error": { "code", "message", "details?", "requestId" } }`.',
    '',
    '"Access" is what the server demands: **Public** (no login), **Signed in** (any logged-in user, about their own account), **Owner only**, or the permission(s) listed, **all** of which are needed. Permissions are described in [rbac.md](rbac.md).',
    '',
  ];
  for (const [group, list] of groups) {
    lines.push(`## ${group}`, '', '| Method | Path | Access |', '|---|---|---|');
    for (const r of list) lines.push(`| ${r.method} | \`${r.path}\` | ${r.access} |`);
    lines.push('');
  }
  lines.push(`${routes.length} endpoints.`, '');
  return lines.join('\n');
}

export function renderRbacDoc() {
  const header = ['Permission', 'What it allows', ...ROLE_KEYS.map((k) => ROLES[k].name)];
  const lines = [
    '# Roles and permissions',
    '',
    NOTE,
    '',
    'Roles give a default set of permissions. The Owner (and an Administrator, within their limits) can add or remove single permissions for one member; nobody can manage someone of equal or higher rank, and only the Owner can hand out `users.manage`. The server checks the permission on every request; the screens only use this table to hide buttons.',
    '',
    `| ${header.join(' | ')} |`,
    `|${header.map((_, i) => (i < 2 ? '---' : ':-:')).join('|')}|`,
  ];
  for (const key of PERMISSION_KEYS) {
    const cells = ROLE_KEYS.map((role) => (ROLE_PERMISSIONS[role].includes(key) ? '✅' : '—'));
    lines.push(`| \`${key}\` | ${PERMISSIONS[key]} | ${cells.join(' | ')} |`);
  }
  lines.push('', 'Two rules combine permissions: who owes what (balances, outstanding and overdue reports) needs `ledger.view` as well as the report permission, and exporting a ledger needs `ledger.view` and `reports.export`.', '');
  return lines.join('\n');
}
